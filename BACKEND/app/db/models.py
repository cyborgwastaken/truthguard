"""Database tables. They mirror the Pydantic records in AGENT/truthguard_agent/schemas/models.py.

Missing metadata is stored as NULL, never as a made-up value. document_id and chunk_id are the
stable primary keys that citations point to.
"""
from __future__ import annotations

from datetime import date, datetime
from typing import Optional

from sqlalchemy import (
    Computed,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .base import Base


class DocumentRow(Base):
    __tablename__ = "documents"

    document_id: Mapped[str] = mapped_column(String(200), primary_key=True)
    title: Mapped[str] = mapped_column(Text)
    content: Mapped[str] = mapped_column(Text)
    content_hash: Mapped[str] = mapped_column(String(64), index=True)
    version: Mapped[Optional[str]] = mapped_column(String(64))
    created_at: Mapped[Optional[date]] = mapped_column(Date)
    effective_date: Mapped[Optional[date]] = mapped_column(Date)
    authority_level: Mapped[str] = mapped_column(String(32), default="unknown")
    # Deliberately not a foreign key: the superseded document may be ingested later (or never).
    supersedes_document_id: Mapped[Optional[str]] = mapped_column(String(200), index=True)
    source: Mapped[Optional[str]] = mapped_column(Text)
    ingested_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    chunks: Mapped[list["ChunkRow"]] = relationship(
        back_populates="document", cascade="all, delete-orphan", order_by="ChunkRow.chunk_index"
    )


class ChunkRow(Base):
    __tablename__ = "chunks"
    __table_args__ = (
        UniqueConstraint("document_id", "chunk_index"),
        Index("ix_chunks_tsv", "tsv", postgresql_using="gin"),
    )

    chunk_id: Mapped[str] = mapped_column(String(260), primary_key=True)
    document_id: Mapped[str] = mapped_column(
        ForeignKey("documents.document_id", ondelete="CASCADE"), index=True
    )
    chunk_index: Mapped[int] = mapped_column(Integer)
    text: Mapped[str] = mapped_column(Text)
    start_offset: Mapped[int] = mapped_column(Integer)
    end_offset: Mapped[int] = mapped_column(Integer)
    # Generated by Postgres; used for full-text search (T07).
    tsv: Mapped[str] = mapped_column(TSVECTOR, Computed("to_tsvector('english', text)", persisted=True))

    document: Mapped[DocumentRow] = relationship(back_populates="chunks")


class AnswerRow(Base):
    __tablename__ = "answers"

    answer_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    question: Mapped[str] = mapped_column(Text)
    answer: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(String(32), index=True)
    conflicts_detected: Mapped[int] = mapped_column(Integer, default=0)
    resolution_reason: Mapped[Optional[str]] = mapped_column(Text)
    model_version: Mapped[Optional[str]] = mapped_column(String(100))
    prompt_version: Mapped[Optional[str]] = mapped_column(String(100))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    # The question date the answer was judged as of, and the whole record (answer + verification) as JSON, so
    # an answer can be shown again exactly as it was produced.
    as_of: Mapped[Optional[date]] = mapped_column(Date)
    details: Mapped[Optional[dict]] = mapped_column(JSONB)

    claims: Mapped[list["ClaimRow"]] = relationship(back_populates="answer", cascade="all, delete-orphan")
    citations: Mapped[list["AnswerCitationRow"]] = relationship(
        back_populates="answer", cascade="all, delete-orphan"
    )


class AnswerCitationRow(Base):
    """Citations shown with the final answer (FinalAnswer.citations)."""

    __tablename__ = "answer_citations"

    answer_id: Mapped[str] = mapped_column(
        ForeignKey("answers.answer_id", ondelete="CASCADE"), primary_key=True
    )
    chunk_id: Mapped[str] = mapped_column(ForeignKey("chunks.chunk_id"), primary_key=True)
    source_id: Mapped[str] = mapped_column(String(200))

    answer: Mapped[AnswerRow] = relationship(back_populates="citations")


class ClaimRow(Base):
    __tablename__ = "claims"

    claim_id: Mapped[str] = mapped_column(String(80), primary_key=True)
    answer_id: Mapped[str] = mapped_column(
        ForeignKey("answers.answer_id", ondelete="CASCADE"), index=True
    )
    text: Mapped[str] = mapped_column(Text)
    claim_type: Mapped[str] = mapped_column(String(32), default="factual")
    status: Mapped[str] = mapped_column(String(32), default="unverified")

    answer: Mapped[AnswerRow] = relationship(back_populates="claims")
    evidence_links: Mapped[list["EvidenceLinkRow"]] = relationship(
        back_populates="claim", cascade="all, delete-orphan"
    )


class EvidenceLinkRow(Base):
    __tablename__ = "evidence_links"
    __table_args__ = (UniqueConstraint("claim_id", "chunk_id", "relation"),)

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    claim_id: Mapped[str] = mapped_column(
        ForeignKey("claims.claim_id", ondelete="CASCADE"), index=True
    )
    chunk_id: Mapped[str] = mapped_column(ForeignKey("chunks.chunk_id"), index=True)
    source_id: Mapped[str] = mapped_column(String(200))
    relation: Mapped[str] = mapped_column(String(16))  # supports | contradicts | context
    rationale: Mapped[str] = mapped_column(Text, default="")
    verifier_version: Mapped[str] = mapped_column(String(100), default="")

    claim: Mapped[ClaimRow] = relationship(back_populates="evidence_links")
